"""Génère les icônes par défaut du lobby (web/assets) : `python3 tools/make_icons.py`.

icon-error.png   : affichée quand la cartouche est illisible ou ne contient pas de jeu.
icon-default.png : affichée quand le jeu n'a pas de fichier icon.png.
Remplacer ces deux fichiers par de vraies images si besoin.
"""
import struct
import zlib
from pathlib import Path

SCALE = 4
CROSS = """
................
.##..........##.
.###........###.
..###......###..
...###....###...
....###..###....
.....######.....
......####......
......####......
.....######.....
....###..###....
...###....###...
..###......###..
.###........###.
.##..........##.
................
"""
QUESTION = """
................
.....######.....
....########....
...###....###...
...##......##...
...........##...
..........###...
.........###....
........###.....
.......###......
.......##.......
.......##.......
................
.......##.......
.......##.......
................
"""


def png(art: str, background: tuple, foreground: tuple) -> bytes:
    rows = [line for line in art.strip().splitlines()]
    raw = b""
    for row in rows:
        line = b"".join(bytes(foreground if char == "#" else background) * SCALE for char in row)
        raw += (b"\x00" + line) * SCALE
    size = len(rows) * SCALE

    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


if __name__ == "__main__":
    out = Path(__file__).resolve().parent.parent / "web" / "assets"
    out.mkdir(parents=True, exist_ok=True)
    (out / "icon-error.png").write_bytes(png(CROSS, (58, 13, 18), (255, 77, 90)))
    (out / "icon-default.png").write_bytes(png(QUESTION, (28, 33, 64), (255, 210, 63)))
    print("Icônes écrites dans", out)
