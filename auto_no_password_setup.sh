#!/bin/bash
# auto_no_password_setup.sh
# Idempotent: détecte s'il a déjà agi et évite de relancer les actions lourdes.
# Usage: sudo ./auto_no_password_setup.sh [--force] [--status]
set -euo pipefail

MARKER_FILE="/etc/retro_setup_done"
TMP_MARKER="/tmp/retro_setup_done.tmp"

log()    { echo -e "\e[1;34m[INFO]\e[0m $*"; }
warn()   { echo -e "\e[1;33m[WARN]\e[0m $*"; }
err()    { echo -e "\e[1;31m[ERROR]\e[0m $*" >&2; }

# --- Argument parsing ---
FORCE="no"
if [ "${1-}" = "--force" ]; then
  FORCE="yes"
elif [ "${1-}" = "--status" ]; then
  if [ -f "$MARKER_FILE" ]; then
    echo "INSTALLED"
    cat "$MARKER_FILE"
  else
    echo "NOT_INSTALLED"
  fi
  exit 0
fi

# Vérifier qu'on est root
if [ "$EUID" -ne 0 ]; then
  err "Ce script doit être exécuté en root. Exemple: sudo $0"
  exit 1
fi

# Si déjà installé et pas de --force, on quitte proprement
if [ -f "$MARKER_FILE" ] && [ "$FORCE" != "yes" ]; then
  log "Installation déjà effectuée (marqueur présent : $MARKER_FILE). Rien à faire."
  exit 0
fi

# Déterminer l'utilisateur cible (celui qui a lancé sudo)
if [ -n "${SUDO_USER-}" ] && [ "$SUDO_USER" != "root" ]; then
  TARGET_USER="$SUDO_USER"
else
  # fallback
  if [ -n "${USER-}" ] && [ "$USER" != "root" ]; then
    TARGET_USER="$USER"
  else
    err "Impossible de déterminer l'utilisateur cible. Lancez le script via 'sudo' depuis le compte utilisateur souhaité."
    exit 1
  fi
fi
log "Utilisateur cible : $TARGET_USER"

# --- Fonctions de nettoyage / succès ---
on_error() {
  warn "Une erreur est survenue. Le marqueur ne sera pas créé."
  [ -f "$TMP_MARKER" ] && rm -f "$TMP_MARKER"
}
trap on_error ERR

# --- Actions idempotentes ---
GROUPS_TO_ADD=(sudo input gpio video plugdev seat audio dialout)

for g in "${GROUPS_TO_ADD[@]}"; do
  if ! getent group "$g" >/dev/null 2>&1; then
    log "Création du groupe manquant : $g"
    groupadd "$g" || true
  fi
  if id -nG "$TARGET_USER" | grep -qw "$g"; then
    log "Utilisateur $TARGET_USER déjà membre du groupe $g"
  else
    log "Ajout de $TARGET_USER au groupe $g"
    usermod -aG "$g" "$TARGET_USER"
  fi
done

# --- Autologin sur tty1 (idempotent) ---
GETTY_DIR="/etc/systemd/system/getty@tty1.service.d"
AUTOCONF="$GETTY_DIR/autologin.conf"
AGETTY_PATH="$(command -v agetty || echo /sbin/agetty)"
mkdir -p "$GETTY_DIR"

cat > "$AUTOCONF" <<EOF
[Service]
ExecStart=
ExecStart=-$AGETTY_PATH --autologin $TARGET_USER --noclear %I \$TERM
EOF

chmod 0644 "$AUTOCONF"
log "Autologin configuré pour $TARGET_USER (fichier $AUTOCONF)"

# --- Sudoers sans mot de passe (idempotent) ---
SUDOERS_FILE="/etc/sudoers.d/99_${TARGET_USER}_nopasswd"
cat > "$SUDOERS_FILE" <<EOF
# Grant $TARGET_USER passwordless sudo (generated by auto_no_password_setup.sh)
$TARGET_USER ALL=(ALL) NOPASSWD: ALL
EOF
chmod 0440 "$SUDOERS_FILE"
# vérifier la syntaxe
if visudo -cf "$SUDOERS_FILE"; then
  log "Sudoers OK ($SUDOERS_FILE)"
else
  err "Erreur de syntaxe sudoers."
  exit 1
fi

# --- Reload systemd et restart getty (safe) ---
log "Reload systemd et redémarrage getty@tty1"
systemctl daemon-reload
# restart peut échouer sur certains systèmes conteneurisés, on ne plante pas pour autant
if ! systemctl restart getty@tty1.service >/dev/null 2>&1; then
  warn "Impossible de redémarrer getty@tty1.service (peut être normal)."
fi

# --- Tout s'est bien déroulé : créer le marqueur atomiquement ---
{
  echo "InstalledOn: $(date -Iseconds)"
  echo "User: $TARGET_USER"
  echo "GroupsAdded: ${GROUPS_TO_ADD[*]}"
  echo "Autologin: $AUTOCONF"
  echo "Sudoers: $SUDOERS_FILE"
} > "$TMP_MARKER"

# mv atomique
mv "$TMP_MARKER" "$MARKER_FILE"
chmod 0644 "$MARKER_FILE"

log "Installation terminée avec succès. Marqueur créé : $MARKER_FILE"

cat <<EOF

Résumé :
- Autologin activé pour : $TARGET_USER (tty1)
- Sudo sans mot de passe activé : $SUDOERS_FILE
- Groupes ajoutés : ${GROUPS_TO_ADD[*]}

Ce script est idempotent : il ne réappliquera pas les mêmes actions si le marqueur existe.
Pour forcer une ré-exécution, lance avec : sudo $0 --force
Pour vérifier le statut : sudo $0 --status

Important :
- Si tu veux revenir en arrière, supprime $MARKER_FILE et supprime manuellement $AUTOCONF et $SUDOERS_FILE, puis relance systemctl daemon-reload.
EOF

exit 0
